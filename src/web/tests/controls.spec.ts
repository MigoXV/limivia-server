test('ADC isolates pins, exports only selected samples and clears on reconnect', async ({
  page,
}) => {
  const device = await installDevice(page, 'ble')
  await page.goto('/')
  await connectDevice(page)
  await page.getByRole('button', { name: '模拟采集', exact: true }).click()
  device.sample(0, 300, null)
  device.sample(1, 2400, 1600)
  await expect(page.locator('.adc-readings')).toContainText('300')
  await expect(page.getByRole('heading', { name: '原始读数趋势' })).toBeVisible()
  await page.getByLabel('目标引脚').selectOption('1')
  await expect(page.locator('.adc-readings')).toContainText('2400')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 CSV' }).click()
  const download = await downloadPromise
  const reader = await download.createReadStream()
  let csv = ''
  for await (const chunk of reader) csv += chunk.toString()
  expect(csv).toContain(',1,2400,1600,true')
  expect(csv).not.toContain(',0,300,')
  device.disconnect()
  await expect(page.getByText('上次读数 · 已失效')).toBeVisible()
  await openConnection(page)
  await page.getByRole('button', { name: '连接所选设备' }).click()
  await expect(page.locator('.connection-status')).toHaveText('已连接')
  await expect(page.locator('.adc-readings')).not.toContainText('2400')
  await expect(page.getByRole('button', { name: '导出 CSV' })).toBeDisabled()
})

test('stop all requires confirmation and reconnect never replays writes', async ({ page }) => {
  const device = await installDevice(page, 'ble')
  await page.goto('/')
  await connectDevice(page)
  await page.getByRole('button', { name: '板载定时', exact: true }).click()
  await page.getByRole('button', { name: '启动本地任务' }).click()
  await expect(page.locator('.task-row')).toHaveCount(1)
  device.disconnect()
  await expect(page.locator('.task-row')).toContainText('状态未知')
  await openConnection(page)
  await page.getByRole('button', { name: '连接所选设备' }).click()
  await expect(page.locator('.connection-status')).toHaveText('已连接')
  expect(device.commands.filter((op) => op === 'timer.start')).toHaveLength(1)
  const resources = await openResources(page)
  await resources.getByRole('button', { name: '停止全部输出…' }).click()
  const dialog = page.getByRole('dialog', { name: '停止全部输出？' })
  await dialog.getByRole('button', { name: '取消' }).click()
  expect(device.commands).not.toContain('outputs.stop')
  await resources.getByRole('button', { name: '停止全部输出…' }).click()
  await dialog.getByRole('button', { name: '停止全部输出', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect(device.commands.filter((op) => op === 'outputs.stop')).toHaveLength(1)
  await resources.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.locator('.task-row')).toHaveCount(0)
})
