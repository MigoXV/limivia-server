import { test, expect } from '@playwright/test'
import { installDevice } from './simulated-device'
import { connectDevice, openConnection, openResources } from './helpers'

for (const kind of ['usb', 'ble'] as const) {
  test(`${kind}: handshake, output, PWM, timer, ADC and disconnect`, async ({ page }) => {
    const device = await installDevice(page, kind)
    await page.goto('/')
    await connectDevice(page, kind)
    await page.getByRole('button', { name: '点亮 LED', exact: true }).click()
    await expect(page.getByRole('heading', { name: '已点亮', exact: true })).toBeVisible()
    const resources = await openResources(page)
    await resources.getByRole('button', { name: '释放引脚', exact: true }).click()
    await page
      .getByRole('dialog', { name: '释放 GPIO 13？' })
      .getByRole('button', { name: '释放并读取状态' })
      .click()
    await expect(page.getByRole('dialog', { name: '释放 GPIO 13？' })).not.toBeVisible()
    await resources.getByRole('button', { name: '关闭', exact: true }).click()
    const before = device.commands.length
    await page.getByRole('button', { name: '呼吸演示', exact: true }).click()
    expect(device.commands.slice(before).filter((op) => op !== 'state')).toEqual([])
    await page.getByRole('button', { name: '开始呼吸' }).click()
    await expect(page.getByRole('heading', { name: '呼吸运行中' })).toBeVisible()
    await page.getByRole('button', { name: '开关控制', exact: true }).click()
    const switchDialog = page.getByRole('dialog', { name: '停止呼吸并切换？' })
    await switchDialog.getByRole('button', { name: '取消' }).click()
    await expect(page.getByRole('heading', { name: '呼吸运行中' })).toBeVisible()
    await page.getByRole('button', { name: '开关控制', exact: true }).click()
    await switchDialog.getByRole('button', { name: '停止并读取状态' }).click()
    await expect(switchDialog).not.toBeVisible()
    await expect(page.getByRole('button', { name: '点亮 LED', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: '板载定时', exact: true }).click()
    await page.getByRole('button', { name: '启动本地任务' }).click()
    await expect(page.locator('.task-row')).toContainText('GPIO 0')
    await page.getByRole('button', { name: '停止任务', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '停止任务', exact: true }).click()
    await expect(page.locator('.task-row')).toHaveCount(0)
    await page.getByRole('button', { name: '模拟采集', exact: true }).click()
    await page.getByRole('button', { name: '开始采样' }).click()
    await expect(page.locator('.adc-readings')).toContainText('2048')
    await expect(page.locator('.adc-readings')).toContainText('1500')
    await page.getByRole('button', { name: '停止采样' }).click()
    await expect(page.locator('.sampling-status')).toContainText('已停止')
    await expect(page.getByRole('button', { name: '导出 CSV' })).toBeEnabled()
    await page.getByRole('button', { name: '连接详情' }).click()
    await page.getByRole('button', { name: '断开连接…' }).click()
    await page
      .getByRole('dialog', { name: '断开设备连接？' })
      .getByRole('button', { name: '断开连接', exact: true })
      .click()
    await expect(page.getByText('上次读数 · 已失效')).toBeVisible()
    await expect(page.getByRole('button', { name: '开始采样' })).toBeDisabled()
  })
}

test('LED confirmation and feedback stay aligned while waiting for the device', async ({
  page,
}) => {
  const device = await installDevice(page, 'ble')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await connectDevice(page)
  const button = page.locator('.led-controls .primary')
  const confirmation = page.locator('.led-confirmation')
  const secondary = page.locator('.led-secondary')
  const before = await button.boundingBox()
  const confirmationBefore = await confirmation.boundingBox()
  const secondaryBefore = await secondary.boundingBox()
  await expect(page.locator('.operation-feedback')).toContainText('设备已确认熄灭。')
  await page.screenshot({ path: '../../artifacts/figma-sync/led-off-1440.png' })
  device.delayNext('gpio.set')
  await button.click()
  await expect(page.getByRole('heading', { name: '等待确认' })).toBeVisible()
  await expect(button).toBeDisabled()
  expect(await button.boundingBox()).toEqual(before)
  expect(await confirmation.boundingBox()).toEqual(confirmationBefore)
  expect(await secondary.boundingBox()).toEqual(secondaryBefore)
  await expect(page.locator('.led-indicator')).toHaveClass(/pending/)
  await page.screenshot({ path: '../../artifacts/figma-sync/led-pending-1440.png' })
  device.acknowledge()
  await expect(page.getByRole('heading', { name: '已点亮', exact: true })).toBeVisible()
  expect(await button.boundingBox()).toEqual(before)
  expect(await confirmation.boundingBox()).toEqual(confirmationBefore)
  expect(await secondary.boundingBox()).toEqual(secondaryBefore)
  await expect(page.locator('.operation-feedback')).toContainText('设备已确认点亮。')
  await page.screenshot({ path: '../../artifacts/figma-sync/led-on-1440.png' })
  expect(device.commands.filter((op) => op === 'gpio.set')).toHaveLength(1)
})

test('lost acknowledgement blocks writes until explicit state recovery', async ({ page }) => {
  const device = await installDevice(page, 'ble')
  await page.goto('/')
  await connectDevice(page)
  device.dropNext('gpio.set')
  await page.getByRole('button', { name: '点亮 LED', exact: true }).click()
  await expect(page.getByRole('heading', { name: '结果未知' })).toBeVisible({ timeout: 10000 })
  await expect(page.locator('.led-controls .primary')).toBeDisabled()
  await expect(page.getByRole('alert')).toContainText('不要直接重复提交')
  device.rejectNext('state', 'hardware_error')
  await page.getByRole('button', { name: '读取状态', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('硬件驱动')
  await expect(page.locator('.led-controls .primary')).toBeDisabled()
  await expect(page.getByRole('heading', { name: '结果未知' })).toBeVisible()
  await page.getByRole('button', { name: '读取状态', exact: true }).click()
  await expect(page.getByRole('heading', { name: '已点亮', exact: true })).toBeVisible()
  expect(device.commands.filter((op) => op === 'gpio.set')).toHaveLength(1)
})

